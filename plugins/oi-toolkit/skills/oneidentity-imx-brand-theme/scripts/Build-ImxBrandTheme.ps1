#Requires -Version 7.6
<#
.SYNOPSIS
    Compiles the light and dark brand themes generated by New-ImxBrandTheme.ps1 and runs the blocking checks.
.DESCRIPTION
    sass custom-theme/<id>/<id>-light|dark.scss -> <OutDir>/<id>/<class>.css (the folder copied into the portal
    package), then check-theme-css.mjs: no unscoped difference between the two files, no @font-face, full runtime
    contract; and a size limit. Last output line: JSON { status, css: [{ file, kb }], checks }.
.EXAMPLE
    pwsh -NoProfile -File Build-ImxBrandTheme.ps1 -Id acme -ImxWebDir oim/webportal/imx/imxweb -OutDir oim/webportal/brand/acme/dist
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][ValidatePattern('^[a-z][a-z0-9-]{1,30}$')][string] $Id,
    [Parameter(Mandatory)][string] $ImxWebDir,
    [Parameter(Mandatory)][string] $OutDir
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$MaxCssKb = 600
# Resolve before Push-Location: sass runs inside imxweb, the checks run here.
$OutDir = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($OutDir)
$imxWeb = (Resolve-Path -LiteralPath $ImxWebDir).Path
if (-not (Test-Path -LiteralPath (Join-Path $imxWeb 'node_modules/@angular/material'))) { throw "node_modules missing in ${imxWeb}: run 'npm install' there first." }
$themeDir = Join-Path $imxWeb "custom-theme/$Id"
$palettePartial = Join-Path $themeDir '_brand-palette.scss'
if (-not (Test-Path -LiteralPath $palettePartial)) { throw "No generated theme in ${themeDir}: run New-ImxBrandTheme.ps1 first." }

$classes = @{}
foreach ($kind in 'light', 'dark') {
    $match = Select-String -LiteralPath $palettePartial -Pattern "^\`$$kind-class: ([a-z0-9-]+);" | Select-Object -First 1
    if (-not $match) { throw "`$$kind-class not found in $palettePartial." }
    $classes[$kind] = $match.Matches[0].Groups[1].Value
}

$cssDir = Join-Path $OutDir $Id
New-Item -ItemType Directory -Force $cssDir | Out-Null
$css = [ordered]@{}
Push-Location $imxWeb
try {
    foreach ($kind in 'light', 'dark') {
        $target = Join-Path $cssDir "$($classes[$kind]).css"
        # Deprecation warnings come from upstream partials (same as the official template): hidden.
        $sassOutput = npx sass "custom-theme/$Id/$Id-$kind.scss:$target" --load-path=node_modules --no-source-map --style=compressed --quiet-deps --silence-deprecation=import,global-builtin 2>&1
        if ($LASTEXITCODE -ne 0) { throw "sass failed for ${Id}-${kind}.scss: $($sassOutput -join ' ')" }
        $css[$kind] = $target
    }
}
finally { Pop-Location }

$checkJson = node (Join-Path $PSScriptRoot 'check-theme-css.mjs') $imxWeb $css.light $css.dark $classes.light $classes.dark
$checkExit = $LASTEXITCODE
$checks = $checkJson | Select-Object -Last 1 | ConvertFrom-Json
$sizes = @($css.Values | ForEach-Object { [pscustomobject]@{ file = (Split-Path -Leaf $_); kb = [Math]::Round((Get-Item -LiteralPath $_).Length / 1KB) } })
$tooBig = @($sizes | Where-Object { $_.kb -gt $MaxCssKb })

[ordered]@{
    status = $(if ($checkExit -eq 0 -and $tooBig.Count -eq 0) { 'ok' } else { 'blocked' })
    css    = $sizes
    checks = [ordered]@{
        scopeDiffs      = $checks.scopeDiffs
        scopeExamples   = $checks.scopeExamples
        fontFaces       = $checks.fontFaces
        contractMissing = $checks.contractMissing
        sizeLimitKb     = $MaxCssKb
        tooBig          = @($tooBig | ForEach-Object { $_.file })
    }
} | ConvertTo-Json -Compress -Depth 4
