#Requires -Version 7.6
<#
.SYNOPSIS
    Generates the light and dark Web Portal brand themes of a customer from its brand.json.
.DESCRIPTION
    Writes imxweb/custom-theme/<id>/ (static templates of the kit, the palette partial and the logo partial) and
    imx-theme-config.json next to brand.json. Every generated file is recorded with its hash in
    custom-theme/<id>/.generated.json: a file changed by hand stops the run (status blocked, nothing written).
    Last output line: JSON { status, written, unchanged, blocked, warnings, manualChecks }.
.EXAMPLE
    pwsh -NoProfile -File New-ImxBrandTheme.ps1 -Brand oim/webportal/brand/acme/brand.json -ImxWebDir oim/webportal/imx/imxweb
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string] $Brand,
    [Parameter(Mandatory)][string] $ImxWebDir,
    # Optional: CUSTOMIZATIONS.md whose block <!-- oi-brand-theme:<id>:begin/end --> is (re)written.
    [string] $CustomizationsPath,
    # Height of the embedded logo images (2x the masthead height, for high-DPI screens).
    [ValidateRange(52, 512)][int] $LogoImageHeight = 104
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$kit = Split-Path -Parent $PSScriptRoot
Import-Module (Join-Path $PSScriptRoot 'ImxBrandColor.psm1') -Force
$version = (Get-Content -LiteralPath (Join-Path $kit '../../.claude-plugin/plugin.json') -Raw | ConvertFrom-Json).version
$header = "// GENERATED by oi-toolkit $version — do not edit (skill oneidentity-imx-brand-theme)."
$AlphaThreshold = 16
$PortalApp = 'qer-app-portal'
$Shades = 'blue10', 'blue15', 'blue20', 'blue40', 'blue60', 'blue80', 'blue85', 'blue90', 'orange10', 'orange15', 'orange20', 'orange40', 'orange60', 'orange80', 'orange85', 'orange90'

#region Logos
function Get-ImxContentBounds([System.Drawing.Bitmap] $Bitmap) {
    $rect = [System.Drawing.Rectangle]::new(0, 0, $Bitmap.Width, $Bitmap.Height)
    $data = $Bitmap.LockBits($rect, [System.Drawing.Imaging.ImageLockMode]::ReadOnly, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    try {
        $bytes = [byte[]]::new([Math]::Abs($data.Stride) * $Bitmap.Height)
        [System.Runtime.InteropServices.Marshal]::Copy($data.Scan0, $bytes, 0, $bytes.Length)
    } finally { $Bitmap.UnlockBits($data) }
    $minX = $Bitmap.Width; $minY = $Bitmap.Height; $maxX = -1; $maxY = -1
    for ($y = 0; $y -lt $Bitmap.Height; $y++) {
        $row = $y * $data.Stride
        for ($x = 0; $x -lt $Bitmap.Width; $x++) {
            if ($bytes[$row + $x * 4 + 3] -le $AlphaThreshold) { continue }
            if ($x -lt $minX) { $minX = $x }; if ($x -gt $maxX) { $maxX = $x }
            if ($y -lt $minY) { $minY = $y }; if ($y -gt $maxY) { $maxY = $y }
        }
    }
    if ($maxX -lt 0) { throw 'The logo has no visible pixels (fully transparent?).' }
    return [System.Drawing.Rectangle]::new($minX, $minY, $maxX - $minX + 1, $maxY - $minY + 1)
}

function ConvertTo-ImxLogoDataUri([string] $Path) {
    <# Crops a PNG to its visible pixels, scales it to $LogoImageHeight and returns { Scss, Ratio, Info }. #>
    Add-Type -AssemblyName System.Drawing
    $bitmap = [System.Drawing.Bitmap]::new($Path)
    try {
        $crop = Get-ImxContentBounds $bitmap
        $width = [int][Math]::Round($crop.Width * $LogoImageHeight / $crop.Height)
        $target = [System.Drawing.Bitmap]::new($width, $LogoImageHeight, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
        try {
            $g = [System.Drawing.Graphics]::FromImage($target)
            try {
                $g.InterpolationMode = 'HighQualityBicubic'; $g.PixelOffsetMode = 'HighQuality'; $g.CompositingQuality = 'HighQuality'
                $g.Clear([System.Drawing.Color]::Transparent)
                $g.DrawImage($bitmap, [System.Drawing.Rectangle]::new(0, 0, $width, $LogoImageHeight), $crop, [System.Drawing.GraphicsUnit]::Pixel)
            } finally { $g.Dispose() }
            $stream = [System.IO.MemoryStream]::new()
            try { $target.Save($stream, [System.Drawing.Imaging.ImageFormat]::Png); $png = $stream.ToArray() } finally { $stream.Dispose() }
        } finally { $target.Dispose() }
    } finally { $bitmap.Dispose() }
    return [pscustomobject]@{
        Scss  = "url('data:image/png;base64,$([Convert]::ToBase64String($png))')"
        Ratio = [Math]::Round($width / $LogoImageHeight, 4).ToString([cultureinfo]::InvariantCulture)
        Info  = "$(Split-Path -Leaf $Path): crop $($crop.Width)x$($crop.Height) -> ${width}x$LogoImageHeight, $($png.Length) bytes"
    }
}

function New-ImxLogosPartial($Logos) {
    $lines = [Collections.Generic.List[string]]::new()
    $lines.Add($header)
    $lines.Add("// Logos cropped to their visible area and scaled to ${LogoImageHeight}px height (2x for high-DPI screens).")
    foreach ($name in 'OnBrand', 'OnDark', 'OnLight') {
        $var = 'logo-on-' + $name.Substring(2).ToLowerInvariant()
        $path = $Logos.$name
        $lines.Add('')
        if (-not $path) { $lines.Add("`$${var}: null;"); $lines.Add("`$${var}-ratio: 1;"); continue }
        $logo = ConvertTo-ImxLogoDataUri $path
        $lines.Add("// $($logo.Info)")
        $lines.Add("`$${var}-ratio: $($logo.Ratio);")
        $lines.Add("`$${var}: $($logo.Scss);")
    }
    return ($lines -join "`n") + "`n"
}
#endregion

#region Palette partial
function Format-ImxSassPalette([string] $Name, $Palette, $Contrast, $Extra) {
    $entries = [Collections.Generic.List[string]]::new()
    $contrasts = [Collections.Generic.List[string]]::new()
    foreach ($hue in $Palette.Keys) {
        $entries.Add("  ${hue}: $($Palette[$hue]),")
        $contrasts.Add("    ${hue}: $(if ($Contrast[$hue] -eq 'light') { '$light-primary-text' } else { '$dark-primary-text' }),")
    }
    if ($Extra) {
        $entries.Add("  '$($Extra.Key)': $($Extra.Color),")
        $contrasts.Add("    '$($Extra.Key)': $(if ($Extra.Contrast -eq 'light') { '$light-primary-text' } else { '$dark-primary-text' }),")
    }
    return @("`$${Name}: (") + $entries + @('  contrast: (') + $contrasts + @('  ),', ');') -join "`n"
}

function Get-ImxContractMaps($Colors) {
    $p = $Colors.Palette; $n = $Colors.NeutralPalette; $w = $Colors.WarnPalette
    $base = [ordered]@{
        blue10 = $n['50']; blue15 = $n['50']; blue20 = $n['100']; blue40 = $n['200']
        blue60 = $p['500']; blue80 = $p['700']; blue85 = $p['800']; blue90 = $p['900']
        orange10 = $w['50']; orange15 = $w['50']; orange20 = $w['100']; orange40 = $w['300']
        orange60 = $w['500']; orange80 = $w['700']; orange85 = $w['800']; orange90 = $w['900']
    }
    $fg = [ordered]@{}; foreach ($k in $base.Keys) { $fg[$k] = $base[$k] }
    $fg.blue10 = $n['700']; $fg.blue15 = $n['700']; $fg.blue20 = $n['600']
    foreach ($k in 'blue40', 'blue60', 'blue80', 'blue85', 'blue90') { $fg[$k] = $Colors.DarkAccent }
    $fg.orange40 = $w['300']; $fg.orange60 = $w['300']
    $surface = [ordered]@{}; foreach ($k in $fg.Keys) { $surface[$k] = $fg[$k] }
    $surface.blue40 = $Colors.DarkFill; $surface.blue60 = $Colors.DarkFill
    $surface.blue80 = $n['800']; $surface.blue85 = $n['800']; $surface.blue90 = $n['900']
    return @{ base = $base; 'dark-foreground' = $fg; 'dark-surface' = $surface }
}

function Format-ImxSassStringMap([string] $Name, $Map) {
    return (@("`$${Name}: (") + @($Shades | ForEach-Object { "  ${_}: '$($Map[$_])'," }) + @(');')) -join "`n"
}

function New-ImxPalettePartial($B) {
    $c = $B.Colors
    $accentHue = @($c.Palette.Keys | Where-Object { $c.Palette[$_] -eq $c.DarkAccent } | Select-Object -First 1)
    $extra = $null
    if ($accentHue.Count -eq 0) {
        $extra = @{ Key = 'dark-accent'; Color = $c.DarkAccent; Contrast = $(if ((Get-ImxOnColor $c.DarkAccent) -eq '#ffffff') { 'light' } else { 'dark' }) }
        $accentHueSass = "'dark-accent'"
    } else { $accentHueSass = $accentHue[0] }
    $maps = Get-ImxContractMaps $c
    $lines = @(
        $header
        "// Brand $($B.Id): palettes, layout and runtime contract values, from brand.json."
        "// Palette format: same as @elemental-ui/core/src/styles/_palette.scss."
        ''
        "`$light-class: $($B.LightClass);"
        "`$dark-class: $($B.DarkClass);"
        "`$device-theme: $($B.DeviceTheme);"
        "`$light-masthead: '$($B.Layout.LightMasthead)';"
        "`$dark-masthead: '$($B.Layout.DarkMasthead)';"
        "`$masthead-logo-height: $($B.LogoHeight.Masthead)px;"
        "`$login-logo-height: $($B.LogoHeight.Login)px;"
        ''
        '$dark-primary-text: rgba(black, 0.87);'
        '$light-primary-text: white;'
        "`$brand-primary: $($c.Primary);"
        "`$on-primary: $($c.OnPrimary);"
        '$surface-dark: #1e1e1e;'
        '$on-surface-dark: #f2f2f2;'
        "`$dark-accent: $($c.DarkAccent);"
        "`$dark-accent-hue: $accentHueSass;"
        "`$dark-fill: $($c.DarkFill);"
        "`$on-dark-fill: $($c.OnDarkFill);"
        "`$dark-fill-string: '$($c.DarkFill)';"
        "`$on-dark-fill-string: '$($c.OnDarkFill)';"
        ''
        (Format-ImxSassPalette 'primary-palette' $c.Palette $c.PaletteContrast $extra)
        ''
        (Format-ImxSassPalette 'neutral-palette' $c.NeutralPalette $c.NeutralContrast $null)
        ''
        (Format-ImxSassPalette 'warn-palette' $c.WarnPalette $c.WarnContrast $null)
        ''
        '// One Identity palette shade -> brand color, read by the ccc plugin (BrandThemeService).'
        (Format-ImxSassStringMap 'map-base' $maps.base)
        ''
        (Format-ImxSassStringMap 'map-dark-foreground' $maps.'dark-foreground')
        ''
        (Format-ImxSassStringMap 'map-dark-surface' $maps.'dark-surface')
    )
    return ($lines -join "`n") + "`n"
}
#endregion

#region Config and CUSTOMIZATIONS block
function New-ImxThemeConfig($B) {
    $themes = @(
        [ordered]@{ Name = $B.LightClass; DisplayName = $B.DisplayName.Light; Class = $B.LightClass; Urls = @("../$PortalApp/$($B.Id)/$($B.LightClass).css") }
        [ordered]@{ Name = $B.DarkClass; DisplayName = $B.DisplayName.Dark; Class = $B.DarkClass; Urls = @("../$PortalApp/$($B.Id)/$($B.DarkClass).css") }
    )
    return ([ordered]@{ Themes = $themes } | ConvertTo-Json -Depth 5) + "`n"
}

function Update-ImxCustomizationsBlock([string] $Path, $B) {
    $begin = "<!-- oi-brand-theme:$($B.Id):begin -->"
    $end = "<!-- oi-brand-theme:$($B.Id):end -->"
    $c = $B.Colors
    $body = @(
        $begin
        "Brand theme ``$($B.Id)`` — generated by oi-toolkit $version (skill ``oneidentity-imx-brand-theme``) from ``brand.json``."
        ''
        '| Item | Value |'
        '|---|---|'
        "| Classes | ``$($B.LightClass)`` ($($B.DisplayName.Light)), ``$($B.DarkClass)`` ($($B.DisplayName.Dark)) |"
        "| Primary / dark accent / dark fill | ``$($c.Primary)`` / ``$($c.DarkAccent)`` / ``$($c.DarkFill)`` with ``$($c.OnDarkFill)`` |"
        "| Neutral / warn | ``$($c.Neutral)`` / ``$($c.Warn)`` |"
        "| Layout | light masthead: $($B.Layout.LightMasthead); dark masthead: $($B.Layout.DarkMasthead); Device theme: $($B.DeviceTheme) |"
    ) + @($B.Notes | ForEach-Object { "| Note | $_ |" }) + @($end)
    $block = $body -join "`n"
    $text = if (Test-Path -LiteralPath $Path) { Get-Content -LiteralPath $Path -Raw } else { '' }
    $pattern = [regex]::Escape($begin) + '[\s\S]*?' + [regex]::Escape($end)
    $new = if ($text -match $pattern) { [regex]::Replace($text, $pattern, { $block }) } else { $text.TrimEnd() + "`n`n" + $block + "`n" }
    if ($new -ne $text) { Set-Content -LiteralPath $Path -Value $new -NoNewline -Encoding utf8NoBOM; return $true }
    return $false
}
#endregion

#region Write with hand-edit protection
function Get-ImxHash([string] $Text) {
    return [Convert]::ToHexString([Security.Cryptography.SHA256]::HashData([Text.Encoding]::UTF8.GetBytes($Text)))
}

$b = Read-ImxBrand $Brand
$imxWeb = (Resolve-Path -LiteralPath $ImxWebDir).Path
$themeDir = Join-Path $imxWeb "custom-theme/$($b.Id)"
$templates = Join-Path $kit 'templates/scss'
$static = { param($file) $header + "`n" + (Get-Content -LiteralPath (Join-Path $templates $file) -Raw) }

$targets = [ordered]@{
    "custom-theme/$($b.Id)/_brand-base.scss"          = & $static '_brand-base.scss'
    "custom-theme/$($b.Id)/_brand-scoped-theme.scss"  = & $static '_brand-scoped-theme.scss'
    "custom-theme/$($b.Id)/_brand-branding.scss"      = & $static '_brand-branding.scss'
    "custom-theme/$($b.Id)/_brand-palette.scss"       = New-ImxPalettePartial $b
    "custom-theme/$($b.Id)/_brand-logos.scss"         = New-ImxLogosPartial $b.Logos
    "custom-theme/$($b.Id)/$($b.Id)-light.scss"       = & $static 'brand-light.scss'
    "custom-theme/$($b.Id)/$($b.Id)-dark.scss"        = & $static 'brand-dark.scss'
    'brand-config/imx-theme-config.json'              = New-ImxThemeConfig $b
}
$resolve = { param($rel) if ($rel -like 'brand-config/*') { Join-Path $b.SourceDir (Split-Path -Leaf $rel) } else { Join-Path $imxWeb $rel } }

$recordPath = Join-Path $themeDir '.generated.json'
$record = if (Test-Path -LiteralPath $recordPath) { Get-Content -LiteralPath $recordPath -Raw | ConvertFrom-Json -AsHashtable } else { @{} }
$written = [Collections.Generic.List[string]]::new(); $unchanged = [Collections.Generic.List[string]]::new(); $blocked = [Collections.Generic.List[string]]::new()
$toWrite = [ordered]@{}
foreach ($rel in $targets.Keys) {
    $path = & $resolve $rel
    $content = $targets[$rel]
    if (Test-Path -LiteralPath $path) {
        $current = Get-Content -LiteralPath $path -Raw
        if ($current -eq $content) { $unchanged.Add($rel); continue }
        if (-not $record.ContainsKey($rel) -or $record[$rel] -ne (Get-ImxHash $current)) { $blocked.Add($rel); continue }
    }
    $toWrite[$rel] = $content
}

$status = 'ok'
if ($blocked.Count -gt 0) {
    $status = 'blocked'
} else {
    foreach ($rel in $toWrite.Keys) {
        $path = & $resolve $rel
        New-Item -ItemType Directory -Force (Split-Path -Parent $path) | Out-Null
        Set-Content -LiteralPath $path -Value $toWrite[$rel] -NoNewline -Encoding utf8NoBOM
        $written.Add($rel)
    }
    $newRecord = [ordered]@{}
    foreach ($rel in $targets.Keys) { $newRecord[$rel] = Get-ImxHash $targets[$rel] }
    $recordText = ($newRecord | ConvertTo-Json) + "`n"
    if (-not (Test-Path -LiteralPath $recordPath) -or (Get-Content -LiteralPath $recordPath -Raw) -ne $recordText) {
        Set-Content -LiteralPath $recordPath -Value $recordText -NoNewline -Encoding utf8NoBOM
    }
    if ($CustomizationsPath -and (Update-ImxCustomizationsBlock $CustomizationsPath $b)) { $written.Add('CUSTOMIZATIONS block') }
}

[ordered]@{
    status       = $status
    written      = $written.ToArray()
    unchanged    = $unchanged.ToArray()
    blocked      = $blocked.ToArray()
    warnings     = $b.Warnings
    manualChecks = @('CompanyLogoUrl empty')
} | ConvertTo-Json -Compress
#endregion
